// Command gen reads shared/authz/permissions.yaml — the single source of
// truth for DAMP's RBAC model — and emits:
//
//   - shared/authz/generated/permissions.go   (Go: auth-proxy's role→permission table)
//   - shared/authz/generated/permissions.ts   (TypeScript: @damp/authz for the frontend)
//   - shared/authz/generated/keycloak-roles.json (merged into the Keycloak realm import)
//
// Run via `make authz-gen` or `go run ./shared/authz/gen` from the repo root.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type permissionDef struct {
	Description string `yaml:"description"`
}

type roleDef struct {
	Description string   `yaml:"description"`
	Permissions []string `yaml:"permissions"`
}

type permissionsFile struct {
	Permissions map[string]permissionDef `yaml:"permissions"`
	Roles       map[string]roleDef       `yaml:"roles"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "authz-gen: "+err.Error())
		os.Exit(1)
	}
}

func run() error {
	repoRoot, err := findRepoRoot()
	if err != nil {
		return err
	}

	srcPath := filepath.Join(repoRoot, "shared", "authz", "permissions.yaml")
	raw, err := os.ReadFile(srcPath)
	if err != nil {
		return fmt.Errorf("reading %s: %w", srcPath, err)
	}

	var pf permissionsFile
	if err := yaml.Unmarshal(raw, &pf); err != nil {
		return fmt.Errorf("parsing %s: %w", srcPath, err)
	}

	if err := validate(pf); err != nil {
		return err
	}

	permNames := sortedKeys(pf.Permissions)
	roleNames := sortedKeys(pf.Roles)

	outDir := filepath.Join(repoRoot, "shared", "authz", "generated")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	if err := writeGo(filepath.Join(outDir, "permissions.go"), pf, permNames, roleNames); err != nil {
		return err
	}
	if err := writeTS(filepath.Join(outDir, "permissions.ts"), pf, permNames, roleNames); err != nil {
		return err
	}
	if err := writeKeycloakRoles(filepath.Join(outDir, "keycloak-roles.json"), pf, roleNames); err != nil {
		return err
	}

	fmt.Printf("authz-gen: wrote %d permissions, %d roles to %s\n", len(permNames), len(roleNames), outDir)
	return nil
}

// validate catches the two mistakes that would otherwise ship silently: a
// role granting a permission that doesn't exist in the permissions block,
// and (informationally) reports each role's permission count so a
// regression like "admin quietly gained/lost a permission" shows up in the
// generator's own output, not just a diff nobody reads closely.
func validate(pf permissionsFile) error {
	var problems []string
	for roleName, role := range pf.Roles {
		for _, perm := range role.Permissions {
			if _, ok := pf.Permissions[perm]; !ok {
				problems = append(problems, fmt.Sprintf("role %q grants undefined permission %q", roleName, perm))
			}
		}
	}
	if len(problems) > 0 {
		sort.Strings(problems)
		return fmt.Errorf("invalid permissions.yaml (%d problem(s)):\n  - %s", len(problems), strings.Join(problems, "\n  - "))
	}
	return nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// goIdent turns "wallets:read:own" into "WalletsReadOwn" and "customer" into
// "Customer" — split on non-alphanumeric separators, title-case each part.
func goIdent(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return r == ':' || r == '_' || r == '-'
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}

func writeGo(path string, pf permissionsFile, permNames, roleNames []string) error {
	var b strings.Builder
	b.WriteString("// Code generated by shared/authz/gen from ../permissions.yaml. DO NOT EDIT.\n")
	b.WriteString("package authz\n\n")

	b.WriteString("// Role is one of DAMP's 6 realm roles, as issued by Keycloak.\n")
	b.WriteString("type Role string\n\n")
	b.WriteString("// Permission is one of DAMP's fine-grained permissions. Tokens never carry\n")
	b.WriteString("// these directly — auth-proxy expands a token's roles to a permission set\n")
	b.WriteString("// on every request via RolePermissions, so a permission change takes effect\n")
	b.WriteString("// immediately instead of waiting for every issued token to expire.\n")
	b.WriteString("type Permission string\n\n")

	b.WriteString("const (\n")
	for _, name := range roleNames {
		fmt.Fprintf(&b, "\t// %s\n\tRole%s Role = %q\n", pf.Roles[name].Description, goIdent(name), name)
	}
	b.WriteString(")\n\n")

	b.WriteString("const (\n")
	for _, name := range permNames {
		fmt.Fprintf(&b, "\t// %s\n\tPermission%s Permission = %q\n", pf.Permissions[name].Description, goIdent(name), name)
	}
	b.WriteString(")\n\n")

	b.WriteString("// RolePermissions maps each role to its granted permission set. See\n")
	b.WriteString("// permissions.yaml for the segregation-of-duties rationale behind any role\n")
	b.WriteString("// not holding a permission you might expect it to.\n")
	b.WriteString("var RolePermissions = map[Role][]Permission{\n")
	for _, name := range roleNames {
		fmt.Fprintf(&b, "\tRole%s: {\n", goIdent(name))
		for _, perm := range pf.Roles[name].Permissions {
			fmt.Fprintf(&b, "\t\tPermission%s,\n", goIdent(perm))
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString(`// HasPermission reports whether role is granted permission.
func HasPermission(role Role, permission Permission) bool {
	for _, p := range RolePermissions[role] {
		if p == permission {
			return true
		}
	}
	return false
}

// ExpandRoles unions the permission sets of one or more roles — a token can
// carry more than one realm role (e.g. a compliance officer who is also an
// auditor).
func ExpandRoles(roles []Role) []Permission {
	seen := make(map[Permission]bool)
	var out []Permission
	for _, r := range roles {
		for _, p := range RolePermissions[r] {
			if !seen[p] {
				seen[p] = true
				out = append(out, p)
			}
		}
	}
	return out
}
`)

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func writeTS(path string, pf permissionsFile, permNames, roleNames []string) error {
	var b strings.Builder
	b.WriteString("// Code generated by shared/authz/gen from ../permissions.yaml. DO NOT EDIT.\n\n")

	b.WriteString("export type Role =\n")
	for i, name := range roleNames {
		sep := " |"
		if i == len(roleNames)-1 {
			sep = ";"
		}
		fmt.Fprintf(&b, "  %q%s\n", name, sep)
	}
	b.WriteString("\n")

	b.WriteString("export type Permission =\n")
	for i, name := range permNames {
		sep := " |"
		if i == len(permNames)-1 {
			sep = ";"
		}
		fmt.Fprintf(&b, "  %q%s\n", name, sep)
	}
	b.WriteString("\n")

	b.WriteString("export const ROLE_PERMISSIONS: Record<Role, Permission[]> = {\n")
	for _, name := range roleNames {
		fmt.Fprintf(&b, "  %q: [\n", name)
		for _, perm := range pf.Roles[name].Permissions {
			fmt.Fprintf(&b, "    %q,\n", perm)
		}
		b.WriteString("  ],\n")
	}
	b.WriteString("};\n\n")

	b.WriteString(`export function hasPermission(role: Role, permission: Permission): boolean {
  return ROLE_PERMISSIONS[role].includes(permission);
}

export function expandRoles(roles: Role[]): Permission[] {
  const seen = new Set<Permission>();
  for (const role of roles) {
    for (const permission of ROLE_PERMISSIONS[role]) {
      seen.add(permission);
    }
  }
  return Array.from(seen);
}
`)

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func writeKeycloakRoles(path string, pf permissionsFile, roleNames []string) error {
	var b strings.Builder
	b.WriteString("[\n")
	for i, name := range roleNames {
		comma := ","
		if i == len(roleNames)-1 {
			comma = ""
		}
		fmt.Fprintf(&b, "  {\"name\": %q, \"description\": %q}%s\n", name, pf.Roles[name].Description, comma)
	}
	b.WriteString("]\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func findRepoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.work")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.work found above %s", dir)
		}
		dir = parent
	}
}
